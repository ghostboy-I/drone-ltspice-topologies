"""Phase 0: detect installed tools and write ENVIRONMENT.md. Re-run on any new machine."""
import importlib, os, platform, shutil, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT


def sh(cmd):
    try:
        return subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:
        return ""


OF = "source /opt/openfoam13/etc/bashrc 2>/dev/null; "
rows = [
    ("OpenFOAM", sh(OF + 'echo "$WM_PROJECT $WM_PROJECT_VERSION ($WM_COMPILER, $WM_MPLIB, $WM_PRECISION_OPTION)"') + "; package " + sh("dpkg-query -W -f='${Version}' openfoam13 2>/dev/null"),
     "Foundation fork (openfoam.org), `foamRun -solver <module>` interface. Source `/opt/openfoam13/etc/bashrc` first."),
    ("snappyHexMesh / blockMesh / surfaceCheck", "present" if sh(OF + "command -v snappyHexMesh") else "MISSING", "ships with OpenFOAM 13"),
    ("cfMesh (cartesianMesh)", sh(OF + "command -v cartesianMesh") or "MISSING", "user build under ~/OpenFOAM"),
    ("OpenMPI", sh("dpkg-query -W -f='${Version}' openmpi-bin 2>/dev/null") or "MISSING", ""),
    ("ParaView / pvpython", sh("pvpython --version 2>&1 | head -1") or "MISSING", ""),
    ("CalculiX ccx", sh("dpkg-query -W -f='${Version}' calculix-ccx 2>/dev/null") or "MISSING", "FE solver for Phase 5"),
    ("gmsh", sh("gmsh --version 2>&1 | head -1") or "MISSING", ""),
    ("XFOIL", (os.path.join("tools", "xfoil_pkg", "usr", "bin", "xfoil") + " (6.99, Ubuntu package unpacked locally by tools/get_xfoil.sh, run with the no-FPE-trap shim)")
     if os.path.exists(os.path.join(ROOT, "tools", "xfoil_pkg", "usr", "bin", "xfoil")) else (shutil.which("xfoil") or "MISSING"),
     "Phase 2 polars. `tools/get_xfoil.sh` fetches it without root, or `sudo apt install xfoil`"),
    ("pdftoppm", shutil.which("pdftoppm") or "MISSING", "for checking the design PDF"),
    ("gcc", sh("gcc --version | head -1"), ""),
    ("Python", platform.python_version(), ""),
]
for mod, note in (("numpy", ""), ("matplotlib", ""), ("yaml", ""), ("scipy", "`sudo apt install python3-scipy` (optimiser, Phase 2)"),
                  ("pytest", "`sudo apt install python3-pytest`; until then `python3 run_tests.py`"),
                  ("neuralfoil", "optional alternative to XFOIL; needs pip (`sudo apt install python3-pip python3-venv`)"),
                  ("cadquery", "optional (Phase 3 STEP export); needs pip. Fallback is own lofting to STL plus gmsh/OpenCASCADE for STEP")):
    try:
        ver = getattr(importlib.import_module(mod), "__version__", "present")
    except Exception:
        ver = "MISSING"
    rows.append((f"Python: {mod}", ver, note if ver == "MISSING" else ""))
mem = sh("free -g | awk '/Mem:/{print $2\" GB total, \"$7\" GB available\"}'")
txt = ["# Environment (Phase 0)\n", "Generated by `src/env_report.py`. Tool versions are whatever is installed; nothing is substituted silently.\n",
       f"- Machine: {sh('lscpu | grep \"Model name\" | cut -d: -f2 | xargs')}, {os.cpu_count()} logical CPUs, RAM {mem}",
       f"- OS: {sh('lsb_release -ds')}, kernel {platform.release()}",
       "- RAM is the limit for CFD: at roughly 1–2 GB per million cells, meshes above about 5–8 million cells will not fit. Mesh sizes are planned around that.\n",
       "| Tool | Version / status | Notes |", "|---|---|---|"]
txt += [f"| {a} | {b} | {c} |" for a, b, c in rows]
txt += ["", "## OpenFOAM fork note", "",
        "This is OpenFOAM **Foundation v13**, so cases use `foamRun` with solver modules (`incompressibleFluid`, `fluid`, `shockFluid`), "
        "`MRFProperties`/`fvModels`-style setup and `mover`-based mesh motion with NCC (non-conformal coupling) rather than ESI's `cyclicAMI` "
        "sliding mesh. The brief's solver names (`simpleFoam`, `pimpleFoam`, `rhoSimpleFoam`) map to those modules; ESI syntax will not be mixed in. "
        "The `incompressibleFluid/propeller`, `mixerSRF` and `rotorDisk` tutorials are the reference cases.", "",
        "## Missing and what it blocks", ""]
missing = [(a, c) for a, b, c in rows if b == "MISSING"]
txt += [f"- **{a}**: {c or 'no note'}" for a, c in missing] or ["- Nothing missing."]
txt += ["", "There is no `pip` on this machine (`python3 -m pip` and `ensurepip` are both absent), so this project installed nothing.", ""]
import json
os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
json.dump({"missing": [a.replace("Python: ", "") for a, _ in missing], "tools": {a: b for a, b, _ in rows}},
          open(os.path.join(ROOT, "results", "environment.json"), "w"), indent=1)
open(os.path.join(ROOT, "ENVIRONMENT.md"), "w").write("\n".join(txt))
print("wrote ENVIRONMENT.md")
