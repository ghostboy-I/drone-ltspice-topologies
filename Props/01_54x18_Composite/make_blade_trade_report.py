"""Builds BLADE_TRADE_STUDY.md from results/blade_trade.json. No numbers are typed in here."""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "src"))
from common import ROOT, load_params, load_catalog

o = json.load(open(os.path.join(ROOT, "results", "blade_trade.json")))
p, cat = load_params(), load_catalog()
mass = p["mass"]
C = o["cases"]; names = list(C)
pick = lambda n, rpm: next(s for s in C[n]["sweep"] if s["design_rpm"] == rpm)
S = {n: pick(n, C[n]["selected_rpm"]) for n in names}
L = {n: pick(n, C[n]["lowest_energy_rpm"]) for n in names}
b = S["2-blade 44xx"]; e0 = b["mission"]["pack_wh"]
hc = o["hand_checks"]
bm = cat["props"]["blade_mass_g"]
vendor_blade_g = bm[52] + (54 - 52) / (57 - 52) * (bm[57] - bm[52])     # same linear rule as the diameter study
ref_gain = json.load(open(os.path.join(ROOT, "results", "phase2.json")))["two_point"]["gain_pct"]


def tbl(head, rows):
    s = "| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n"
    return s + "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows) + "\n"


def blade_set_g(s):
    """Rotor blade-set mass: vendor 2-blade 54 in hollow blade mass scaled by total blade volume (same laminate, same wall)."""
    g = vendor_blade_g
    return 2 * g * s["blade_volume_total_cm3"] / b["blade_volume_total_cm3"]


def rows(D):
    r = [["Design hover RPM (sweep point)"] + [f"{D[n]['design_rpm']}" for n in names],
         ["Solidity"] + [f"{D[n]['solidity']:.3f}" for n in names],
         ["Equivalent pitch at 75 % R [in]"] + [f"{D[n]['pitch75_in']:.1f}" for n in names],
         ["Hover FoM"] + [f"{D[n]['hover']['FoM']:.3f}" for n in names],
         ["Hover shaft power [W]: induced / profile"] + [f"{D[n]['P_induced']:.0f} / {D[n]['P_profile']:.0f}" for n in names],
         ["Thrust-weighted section cd in hover"] + [f"{D[n]['cd0_thrust_weighted']:.4f}" for n in names],
         ["Cruise shaft power at 15 m/s, total [W]"] + [f"{D[n]['cruise']['15']['shaft_total']:.0f}" for n in names],
         ["Max outboard α in cruise at 15 m/s [°]"] + [f"{D[n]['cruise']['15']['alpha_max_deg']:.1f}" for n in names],
         ["**Mission pack energy [Wh]**"] + [f"**{D[n]['mission']['pack_wh']:.0f}** ({100*(D[n]['mission']['pack_wh']/e0-1):+.1f} %)" for n in names],
         ["T/W on U15XL at 84 V / fresh pack"] + [f"{D[n]['motor_u15xl_sag']['tw']:.2f} / {D[n]['motor_u15xl_fresh']['tw']:.2f}" for n in names],
         ["Stall margin in hover [°]"] + [f"{D[n]['stall_margin_deg']:.1f}" for n in names],
         ["Blade-set volume per rotor [cm³]"] + [f"{D[n]['blade_volume_total_cm3']:.0f}" for n in names],
         ["Blade-set mass per rotor, scaled from vendor [g]"] + [f"{blade_set_g(D[n]):.0f}" for n in names],
         ["Blade thrust at 15 m/s: mean ± 1P [N]"] + [f"{D[n]['cruise']['15']['blade_T_mean']:.0f} ± {D[n]['cruise']['15']['blade_T_1P']:.0f}" for n in names],
         ["Hub roll moment at 15 m/s: mean ± ripple [N·m] (ripple freq.)"] + [f"{D[n]['hub_15']['roll_mean']:.0f} ± {D[n]['hub_15']['roll_ripple']:.1f} ({D[n]['hub_15']['ripple_freq_per_rev']}P)" for n in names],
         ["Hub thrust ripple at 15 m/s [N]"] + [f"± {D[n]['hub_15']['thrust_ripple']:.1f}" for n in names]]
    return r


def payload_delta(n, D):
    """Payload change vs the 2-blade 44xx baseline at fixed MTOW: battery saved minus extra blade mass (3 rotors). Hub mass not included."""
    out = []
    for e in (mass["pack_wh_per_kg_cited"], mass["pack_wh_per_kg_conservative"]):
        dbatt = (e0 - D[n]["mission"]["pack_wh"]) / e
        dblade = 3 * (blade_set_g(D[n]) - blade_set_g(b)) / 1000
        out.append(dbatt - dblade)
    return out


w = []
w.append("# Blade-count and camber trade at 54″\n")
w.append("Generated by `make_blade_trade_report.py` from `results/blade_trade.json` (`src/blade_trade_study.py`). Do not edit by hand.\n")
w.append("Question: does a 3-blade rotor or a more cambered section (NACA 64xx) make the 54″ prop more efficient for the mission?\n")
w.append("## Answer\n")
s3, s64, sh = S["3-blade 44xx"], S["2-blade 64xx"], S["2-blade 64/44 hybrid"]
pd3 = payload_delta("3-blade 44xx", S); pd64 = payload_delta("2-blade 64xx", S)
w.append(f"- **No option saves more than {100*(1-min(L[n]['mission']['pack_wh'] for n in names)/e0):.1f} % of mission energy.** The Phase 2 blade is close to the best this method can find at 54″, as expected:\n"
         f"  hover power is {100*b['P_induced']/b['hover']['P']:.0f} % induced, and induced power is set by disk area, not by blade shape.\n")
w.append(f"- **64xx inboard only (the hybrid): {100*(sh['mission']['pack_wh']/e0-1):+.1f} %.** Too small to matter. The inboard 40 % of the span carries little thrust.\n")
w.append(f"- **64xx full span: {100*(s64['mission']['pack_wh']/e0-1):+.1f} % at the selected design, {100*(L['2-blade 64xx']['mission']['pack_wh']/e0-1):+.1f} % at its best RPM.** The gain is in cruise, not hover\n"
         f"  (hover FoM {b['hover']['FoM']:.3f} → {s64['hover']['FoM']:.3f}): more camber gives the same lift at a lower angle, so the most loaded\n"
         f"  outboard sections in cruise run at {s64['cruise']['15']['alpha_max_deg']:.1f}° instead of {b['cruise']['15']['alpha_max_deg']:.1f}°, further inside the low-drag range. Payload gain\n"
         f"  {pd64[0]:+.2f} / {pd64[1]:+.2f} kg (303 / 200 Wh/kg). Costs not modelled here: a larger nose-down pitching moment (blade torsion) and\n"
         f"  an earlier stall at low Re.\n")
w.append(f"- **3 blades: {100*(s3['mission']['pack_wh']/e0-1):+.1f} % energy, FoM {b['hover']['FoM']:.3f} → {s3['hover']['FoM']:.3f}, T/W {b['motor_u15xl_sag']['tw']:.2f} → {s3['motor_u15xl_sag']['tw']:.2f}.** The battery saved\n"
         f"  is eaten by the extra blade: payload {pd3[0]:+.2f} / {pd3[1]:+.2f} kg before the heavier 3-blade hub. **The real gain is vibration:** the hub roll-moment\n"
         f"  ripple in cruise drops from ±{b['hub_15']['roll_ripple']:.0f} N·m at 2P to ±{s3['hub_15']['roll_ripple']:.0f} N·m at 3P, and the thrust ripple from ±{b['hub_15']['thrust_ripple']:.0f} N to ±{s3['hub_15']['thrust_ripple']:.0f} N.\n"
         f"  Each blade also carries less: ±{s3['cruise']['15']['blade_T_1P']:.0f} N 1P on {s3['cruise']['15']['blade_T_mean']:.0f} N instead of ±{b['cruise']['15']['blade_T_1P']:.0f} N on {b['cruise']['15']['blade_T_mean']:.0f} N.\n")
w.append("- **Recommendation.** Not worth changing the blade for efficiency. A full-span 6 % camber section is the only option with a\n"
         "  clear energy gain, and it is within the error of the method; revisit it if CFD shows the cruise profile drag matters.\n"
         "  Keep 3 blades in mind as a **fatigue and vibration** fix for Phase 5, not as an efficiency fix.\n")

w.append("## Method\n")
w.append("Each case repeats the Phase 2 hover design (minimum-induced-loss blade, chord cap 0.22 R, root shank, re-twist to the design cl), across\n"
         "the same design-RPM sweep, with the same selection rule: **largest T/W on the U15XL at 84 V among designs with ≥ 4° stall margin that\n"
         "reach T/W 2.0 inside the tip-Mach limit**. No two-point refinement, so the baseline is the *unrefined* Phase 2 blade\n"
         f"({e0:.0f} Wh, regression check against Phase 2's sweep). The refined final blade was {ref_gain:.1f} % better than that and every case here would gain similarly.\n")
w.append("NACA 64xx polars were run in XFOIL on the same grid as the 44xx (4 thicknesses × 5 Re × 4 Mach); "
         f"{len(o['polar_failed_64'])} cases did not converge and were filled from the nearest lower Mach number. The hybrid blade blends the two families by thickness:\n"
         "6 % camber where t/c ≥ 15 % (inboard of about 0.43 R), 4 % where t/c ≤ 12 % (outboard of 0.60 R), linear in between.\n")
w.append("Hub ripple is built by adding the azimuthal loads of N equally spaced blades. For a rigid N-blade rotor every harmonic that is not a\n"
         "multiple of N cancels at the hub, so a 2-blade rotor passes the large 1P blade load through as a 2P hub load, and a 3-blade rotor only passes\n"
         "the much smaller 2P/3P content.\n")

w.append("## Results (design picked by the selection rule)\n")
w.append(tbl(["Quantity"] + names, rows(S)))
w.append("\n## Results (lowest-energy design in each sweep)\n")
w.append(tbl(["Quantity"] + names, rows(L)))
w.append("\n![trade](results/blade_trade.png)\n")

w.append("## Hand calculation vs BEMT\n")
w.append("**Tip loss, 2 → 3 blades.** Prandtl's tip loss shrinks the working disk to an effective radius B R with B ≈ 1 − √(2 C_T) / N.\n"
         f"With C_T = T / (ρ A (ΩR)²) = {hc['CT_h_baseline']:.4f}: B₂ = {hc['B2']:.3f}, B₃ = {hc['B3']:.3f}. Induced power goes as 1/B,\n"
         f"so 3 blades should need {hc['induced_cut_2_to_3_hand_pct']:.1f} % less induced power.\n")
w.append("**Profile power.** P₀ = ρ A (ΩR)³ σ c_d0 / 8, with c_d0 the BEMT's thrust-weighted section drag.\n")
w.append(tbl(["Quantity", "Hand calc", "BEMT", "Diff"], [
    ["Induced power cut, 2 → 3 blades [%]", f"{hc['induced_cut_2_to_3_hand_pct']:.1f}", f"{hc['induced_cut_2_to_3_bemt_pct']:.1f}", f"{hc['induced_cut_2_to_3_bemt_pct']-hc['induced_cut_2_to_3_hand_pct']:+.1f} points"],
    ["Profile power, 2 blades [W]", f"{hc['profile_hand_W_2']:.0f}", f"{hc['profile_bemt_W_2']:.0f}", f"{100*(hc['profile_bemt_W_2']/hc['profile_hand_W_2']-1):+.0f} %"],
    ["Profile power, 3 blades [W]", f"{hc['profile_hand_W_3']:.0f}", f"{hc['profile_bemt_W_3']:.0f}", f"{100*(hc['profile_bemt_W_3']/hc['profile_hand_W_3']-1):+.0f} %"]]))
w.append("\nBoth agree within 10 %. The hand profile formula assumes constant chord and uniform inflow; the BEMT blade is tapered. The 3-blade rotor's\n"
         f"sections run at lower Reynolds number (narrower chord), which is why its c_d0 rises from {b['cd0_thrust_weighted']:.4f} to {s3['cd0_thrust_weighted']:.4f}\n"
         "and its profile power rises while its induced power falls. The net is the small FoM gain.\n")

w.append("## Caveats\n")
w.append("- Same BEMT limits as Phase 2: clean-surface XFOIL drag, no compressibility drag rise, rigid-blade forward flight with prescribed inflow.\n"
         "  The Caradonna–Tung check showed BEMT over-predicting thrust by about 31 % on that rotor, so read these as **relative** differences.\n"
         "- 64xx at high cl and low Re is where XFOIL is least reliable, and that is where its cruise gain comes from.\n"
         "- Blade mass scales the vendor's 2-blade mass by volume; a 3-blade hub (heavier, harder to balance and fold) is not included.\n"
         "- No case was given the two-point refinement; it adds about 2 % to each roughly equally.\n")

open(os.path.join(ROOT, "BLADE_TRADE_STUDY.md"), "w").write("\n".join(w))
print("wrote BLADE_TRADE_STUDY.md")
